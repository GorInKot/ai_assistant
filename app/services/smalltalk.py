"""Ответы на «мета-вопросы» к самому ассистенту: «что ты умеешь?», приветствие, благодарность.

Зачем отдельно от RAG: в базе знаний нет ответа про самого ассистента, поэтому поиск
выдаёт случайный фрагмент или отказ, а локальная модель тратит на это десятки секунд.
Готовый ответ мгновенный, детерминированный и не может выдумать несуществующие функции.

Распознавание — по полному совпадению нормализованного сообщения с шаблоном, а не по
вхождению: «Что вы можете сказать про ЕКТП?» — настоящий вопрос и должен идти в поиск.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Iterable
from urllib.parse import urlparse

KIND_CAPABILITIES = "capabilities"
KIND_GREETING = "greeting"
KIND_THANKS = "thanks"

_GREETING = (
    r"(?:привет(?:ствую)?|здравствуй(?:те)?|добрый (?:день|вечер)|доброе утро|"
    r"хай|hello|hi|hey)"
)

_CAPABILITIES_PATTERNS = [
    re.compile(p)
    for p in (
        r"(?:а )?(?:что|чем) (?:ты|вы)(?: еще| ещё| вообще| у нас)? "
        r"(?:умеешь|умеете|можешь|можете|делаешь|делаете)(?: делать| мне помочь| помочь)?",
        r"на что (?:ты |вы )?(?:способен|способны|годишься|годитесь)",
        r"(?:какие )?(?:у тебя|у вас) (?:есть )?(?:какие )?(?:возможности|функции)",
        r"(?:твои|ваши|какие твои|какие ваши) (?:возможности|функции)",
        r"(?:чем|как) (?:ты |вы )?(?:можешь |можете )?(?:мне )?помочь(?: мне)?",
        r"(?:кто ты|ты кто|кто вы|вы кто|что ты такое|что вы такое)",
        r"(?:расскажи|расскажите) (?:о себе|про себя)|представься|представьтесь",
        r"(?:помощь|справка|help|хелп)",
        r"как (?:с тобой|тобой|с вами|вами) (?:работать|пользоваться)",
        r"что (?:здесь |тут )?можно (?:сделать|спросить)",
    )
]
_GREETING_RE = re.compile(rf"{_GREETING}(?: ассистент)?")
_THANKS_RE = re.compile(
    r"(?:спасибо|благодарю|спс|thanks|thank you)(?: большое| огромное| тебе| вам| за помощь)*"
)


def _normalize(text: str) -> str:
    """Нижний регистр, «ё»→«е», без знаков препинания, схлопнутые пробелы."""
    cleaned = re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е"))
    return " ".join(cleaned.split())


def detect_meta_kind(text: str) -> str | None:
    """`capabilities` | `greeting` | `thanks` | None (обычный вопрос → поиск по базе знаний)."""
    norm = _normalize(text)
    norm = re.sub(r" пожалуйста$| пож$", "", norm)
    if not norm or len(norm.split()) > 10:
        return None

    if _THANKS_RE.fullmatch(norm):
        return KIND_THANKS
    if _GREETING_RE.fullmatch(norm):
        return KIND_GREETING

    # «Привет, что ты умеешь?» — приветствие в начале не мешает вопросу.
    rest = re.sub(rf"^{_GREETING}(?: ассистент)?[ ]?", "", norm)
    return KIND_CAPABILITIES if any(p.fullmatch(rest) for p in _CAPABILITIES_PATTERNS) else None


def is_local_llm(base_url: str | None) -> bool:
    """LLM на этой же машине (Ollama/LM Studio) — тогда данные не уходят наружу."""
    if not base_url:
        return False
    host = (urlparse(base_url).hostname or "").lower()
    return host in {"localhost", "127.0.0.1", "::1", "0.0.0.0"}


def topics_from_processes(processes: Iterable[str]) -> list[str]:
    """Темы базы знаний из названий процессов (папок): «ЕКТП_Транспорт» → «ЕКТП Транспорт»."""
    counts = Counter(p for p in processes if p and p != "Общее")
    return [name.replace("_", " ") for name, _ in counts.most_common()]


def build_reply(kind: str, *, documents: int = 0, topics: list[str] | None = None, local: bool = False) -> str:
    if kind == KIND_THANKS:
        return "Пожалуйста! Если появятся вопросы — спрашивайте."

    if kind == KIND_GREETING:
        return (
            "Здравствуйте! Я корпоративный ассистент. Задайте вопрос по базе знаний "
            "или приложите файл и напишите, что с ним сделать. "
            "Напишите «что ты умеешь?», чтобы увидеть все возможности."
        )

    lines = ["Я корпоративный ассистент. Вот что я умею:", ""]
    if documents and topics:
        lines.append(
            f"**Отвечаю по базе знаний.** Сейчас в ней {documents} документов по темам: "
            f"{', '.join(topics)}. Спрашивайте про процессы, роли, статусы, шаги, формы и "
            "шаблоны — отвечу и покажу источники."
        )
    else:
        lines.append(
            "**Отвечаю по базе знаний.** Спрашивайте про процессы, роли, статусы, шаги, формы "
            "и шаблоны — отвечу и покажу источники."
        )
    lines.append(
        "К ответам прикладываю цитаты из документов и отмечаю утверждения, для которых "
        "в документах опоры не нашлось: их стоит проверить. Оценивайте ответы кнопками "
        "«Полезно / Не полезно»: по ним владельцы базы видят, каких документов не хватает."
    )
    lines += [
        "",
        "**Работаю с файлами.** Приложите файл (скрепка у поля ввода) и напишите, что сделать:",
        "- Excel: показать содержимое, сравнить два файла, объединить несколько файлов с одинаковой структурой;",
        "- Word (.docx, .doc): сделать выжимку, сравнить две версии;",
        "- PDF: перевести в Word или Excel; собрать реестр из нескольких документов "
        "(актов, счетов, писем — до 10 за раз): напишите, например, «составь реестр: номер, дата, "
        "сумма». Сканы распознаю автоматически; значения, которых нет в тексте документа, "
        "подсвечиваю — проверяйте результат.",
        "- Сканы спецификаций (форма ГОСТ 21.110, до 20 файлов): напишите «составь реестр "
        "спецификаций» — соберу все позиции в одну таблицу Excel; правки от руки и неуверенно "
        "прочитанные количества выделю для проверки.",
        "",
        "**Конструктор деталей** (вкладка слева внизу): опишите простую деталь словами — например, "
        "пластину с отверстиями или фланец, — построю 3D-модель с проверкой размеров и массой, "
        "файл STEP можно скачать.",
        "",
        "**Чертёж трассы** (вкладка слева внизу): опишите трассу трубопровода участками — "
        "начерчу эскиз плана с размерами и ведомостью участков (PDF, DWG, DXF).",
        "",
        "Оформление заявок в мои задачи не входит — для этого есть Портал.",
    ]
    if local:
        lines.append("Я работаю локально: вопросы и файлы не передаются во внешние сервисы.")
    lines += [
        "",
        "Примеры: «Какие статусы бывают у заявок в ЕКТП?», «Как проходит периодический "
        "медосмотр?», «Переведи этот PDF в Excel».",
    ]
    return "\n".join(lines)
