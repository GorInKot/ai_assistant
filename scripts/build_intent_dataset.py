PREFIXES = ["пожалуйста, ", "добрый день, ", "привет, ", "слушайте, ", "будьте добры, "]
SUFFIXES = [" пожалуйста", ", спасибо", " срочно"]


def _norm(text: str) -> str:
    """Нормализация для сравнения текстов: без регистра, пунктуации и «ё»."""
    return " ".join(re.sub(r"[^\w\s]", "", text.lower().replace("ё", "е")).split())


def _fill(template: str, rng: random.Random) -> str:
    return re.sub(r"\{(\w+)\}", lambda m: rng.choice(SLOTS[m.group(1)]), template)


def _noise(text: str, rng: random.Random) -> str:
    """Живой стиль набора: без точки, строчная буква, вежливая приставка."""
    roll = rng.random()
    if roll < 0.25:
        text = text[0].lower() + text[1:]
    elif roll < 0.45:
        text = rng.choice(PREFIXES) + text[0].lower() + text[1:]
    elif roll < 0.60:
        text = text.rstrip(".?!") + rng.choice(SUFFIXES)
    if rng.random() < 0.3:
        text = text.rstrip(".?!")
    return text


def _slot_names(template: str) -> list[str]:
    return re.findall(r"\{(\w+)\}", template)


def _variants(template: str, rng: random.Random) -> list[str]:
    """Тексты по шаблону: с подстановками — разные комбинации, без — базовый + шумные."""
    names = _slot_names(template)
    out: list[str] = []
    if names:
        combos = list(itertools.product(*(SLOTS[n] for n in names)))
        rng.shuffle(combos)
        for combo in combos[:VARIANTS_PER_TEMPLATE]:
            text = template
            for name, value in zip(names, combo):
                text = text.replace("{" + name + "}", value, 1)
            out.append(text)
    else:
        out.append(template)
    # шумные копии — для любых шаблонов (короткие реплики «да/нет» особенно)
    out += [_noise(out[0], rng) for _ in range(2 if not names else 1)]
    return out


def _assign_splits(templates: list[str], rng: random.Random) -> dict[str, str]:
    """Шаблоны группы → split. В val и test попадает минимум по одному (если шаблонов ≥3)."""
    shuffled = templates[:]
    rng.shuffle(shuffled)
    n = len(shuffled)
    n_val = max(1, round(n * SPLIT_RATIOS[1])) if n >= 3 else 0
    n_test = max(1, round(n * SPLIT_RATIOS[2])) if n >= 3 else 0
    mapping: dict[str, str] = {}
    for i, tpl in enumerate(shuffled):
        if i < n_test:
            mapping[tpl] = "test"
        elif i < n_test + n_val:
            mapping[tpl] = "val"
        else:
            mapping[tpl] = "train"
    return mapping


def build() -> dict[str, list[dict]]:
    rng = random.Random(SEED)
    eval_texts = {_norm(c["question"]) for c in json.loads(EVAL_CASES.read_text(encoding="utf-8")) if "question" in c}

    splits: dict[str, list[dict]] = {"train": [], "val": [], "test": []}
    seen: set[str] = set()
    counter = 0
    for (intent, rtype), templates in TEMPLATES.items():
        split_of = _assign_splits(templates, rng)
        for tpl in templates:
            for text in _variants(tpl, rng):
                key = _norm(text)
                # дубль внутри датасета или совпадение с реальным eval-кейсом — пропускаем
                if not key or key in seen or key in eval_texts:
                    continue
                seen.add(key)
                counter += 1
                splits[split_of[tpl]].append(
                    {
                        "id": f"ds_{counter:04d}",
                        "text": text,
                        "intent": intent,
                        "request_type": rtype,
                        "template": tpl,
                        "split": split_of[tpl],
                    }
                )
    for rows in splits.values():
        rng.shuffle(rows)
    return splits


def main() -> None:
    splits = build()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, rows in splits.items():
        path = OUT_DIR / f"{name}.jsonl"
        path.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
        by_intent = Counter(r["intent"] for r in rows)
        print(f"{name:5s} {len(rows):4d}  {dict(by_intent)}")
    print(f"→ {OUT_DIR}")


if __name__ == "__main__":
    main()
